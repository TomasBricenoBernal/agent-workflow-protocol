#!/usr/bin/env python3
"""Generate the organization chart in README.md from `.agents/config/org.json`.

The chart is a Mermaid diagram written between the ORG markers in README.md.
Areas and review lines come from org.json; each agent's model and whether it is
installed come from the agent files, so the chart cannot drift from them:

- installed  -> `.claude/agents/<name>.md` exists (solid box)
- in catalog -> only `.agents/agent-catalog/<name>.md` exists (dashed box)

Run after installing or removing an agent, or after editing org.json:

    python3 .agents/planning/scripts/build_org.py
"""

from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
ORG = ROOT / ".agents" / "config" / "org.json"
INSTALLED_DIR = ROOT / ".claude" / "agents"
CATALOG_DIR = ROOT / ".agents" / "agent-catalog"
README = ROOT / "README.md"
START = "<!-- ORG:START (generated by build_org.py - do not edit by hand) -->"
END = "<!-- ORG:END -->"
MODEL_RE = re.compile(r"^model:\s*(\S+)", re.MULTILINE)


def node_id(name: str) -> str:
    return re.sub(r"\W", "_", name)


def agent_names() -> set:
    return {p.stem for folder in (INSTALLED_DIR, CATALOG_DIR) for p in folder.glob("*.md")}


def agent_info(name: str) -> tuple:
    """Return (model, installed) for an agent, reading its file."""
    installed = INSTALLED_DIR / f"{name}.md"
    path = installed if installed.exists() else CATALOG_DIR / f"{name}.md"
    if not path.exists():
        raise SystemExit(f"org.json names `{name}` but no agent file exists for it")
    match = MODEL_RE.search(path.read_text(encoding="utf-8"))
    return (match.group(1) if match else "default", installed.exists())


def render(org: dict) -> str:
    lines = ["```mermaid", "flowchart TD", '    user(["User"]) --> lead["' + org["lead"] + '"]']
    catalog = []
    for area in org["areas"]:
        area_id = "area_" + node_id(area["name"])
        lines.append(f'    subgraph {area_id}["{area["name"]}"]')
        for name in area["agents"]:
            model, installed = agent_info(name)
            lines.append(f'        {node_id(name)}["{name}<br/>{model}"]')
            if not installed:
                catalog.append(node_id(name))
        lines.append("    end")
        lines.append(f"    lead --> {area_id}")
    for review in org.get("reviews", []):
        target = node_id(review["to"]) if "to" in review else "area_" + node_id(review["to_area"])
        lines.append(f'    {node_id(review["from"])} -. "{review["label"]}" .-> {target}')
    if catalog:
        lines.append("    classDef catalog stroke-dasharray: 5 5,opacity:0.6")
        lines.append("    class " + ",".join(catalog) + " catalog")
    lines.append("```")
    return "\n".join(lines)


def block(org: dict) -> str:
    return f"{START}\n{render(org)}\n{END}"


def load_org() -> dict:
    return json.loads(ORG.read_text(encoding="utf-8"))


def main() -> int:
    text = README.read_text(encoding="utf-8")
    if START not in text or END not in text:
        raise SystemExit(f"README.md has no ORG markers; add:\n{START}\n{END}")
    head, rest = text.split(START, 1)
    _, tail = rest.split(END, 1)
    README.write_text(head + block(load_org()) + tail, encoding="utf-8")
    print("Wrote the organization chart to README.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
