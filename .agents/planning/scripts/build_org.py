#!/usr/bin/env python3
"""Generate the organization chart in README.md from `.agents/config/org.json`.

The chart is a Mermaid diagram written between the ORG markers in README.md.
Areas and review lines come from org.json; each agent's model and whether it is
installed come from the agent files, so the chart cannot drift from them.

It has two modes, chosen by whether the project has been set up
(`.agents/context/project_profile.md` exists):

- Template (no profile): shows the installed agents as solid boxes and the
  catalog's default agents as dashed boxes - what a project can start from.
- Project (profile exists): shows only the project's own team, the agents in
  `.claude/agents/`. Catalog agents, areas left empty, and review lines that
  point at agents the project does not have are left out.

Run after installing, creating, or removing an agent, or after editing org.json:

    python3 .agents/planning/scripts/build_org.py
"""

from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
ORG = ROOT / ".agents" / "config" / "org.json"
INSTALLED_DIR = ROOT / ".claude" / "agents"
CATALOG_DIR = ROOT / ".agents" / "agent-catalog"
PROFILE = ROOT / ".agents" / "context" / "project_profile.md"
README = ROOT / "README.md"
START = "<!-- ORG:START (generated by build_org.py - do not edit by hand) -->"
END = "<!-- ORG:END -->"
MODEL_RE = re.compile(r"^model:\s*(\S+)", re.MULTILINE)


def node_id(name: str) -> str:
    return re.sub(r"\W", "_", name)


def agent_files(folder: Path) -> dict:
    """Agent name -> file, ignoring helper files such as `_template.md`."""
    return {p.stem: p for p in folder.glob("*.md") if not p.name.startswith("_")}


def installed_names() -> set:
    return set(agent_files(INSTALLED_DIR))


def agent_names() -> set:
    return installed_names() | set(agent_files(CATALOG_DIR))


def model_of(path: Path) -> str:
    match = MODEL_RE.search(path.read_text(encoding="utf-8"))
    return match.group(1) if match else "default"


def render(org: dict, installed: dict, catalog: dict, configured: bool) -> str:
    """Mermaid chart. `installed` and `catalog` map agent name -> file."""
    lines = ["```mermaid", "flowchart LR", '    user(["User"]) --> lead["' + org["lead"] + '"]']
    shown_agents, shown_areas, dashed = set(), set(), []
    for area in org["areas"]:
        members = []
        for name in area["agents"]:
            if name in installed:
                members.append((name, model_of(installed[name]), True))
            elif name in catalog:
                if not configured:
                    members.append((name, model_of(catalog[name]), False))
            else:
                raise SystemExit(f"org.json names `{name}` but no agent file exists for it")
        if not members:
            continue
        area_id = "area_" + node_id(area["name"])
        shown_areas.add(area["name"])
        lines.append(f'    subgraph {area_id}["{area["name"]}"]')
        for name, model, is_installed in members:
            lines.append(f'        {node_id(name)}["{name}<br/>{model}"]')
            shown_agents.add(name)
            if not is_installed:
                dashed.append(node_id(name))
        lines.append("    end")
        lines.append(f"    lead --> {area_id}")
    for review in org.get("reviews", []):
        if review["from"] not in shown_agents:
            continue
        if "to" in review:
            if review["to"] not in shown_agents:
                continue
            target = node_id(review["to"])
        else:
            if review["to_area"] not in shown_areas:
                continue
            target = "area_" + node_id(review["to_area"])
        lines.append(f'    {node_id(review["from"])} -. "{review["label"]}" .-> {target}')
    if dashed:
        lines.append("    classDef catalog stroke-dasharray: 5 5,opacity:0.6")
        lines.append("    class " + ",".join(dashed) + " catalog")
    lines.append("```")
    return "\n".join(lines)


def unplaced_agents(org: dict, installed: dict) -> list:
    """Installed agents that no area lists; they would be missing from the chart."""
    listed = {name for area in org["areas"] for name in area["agents"]}
    return sorted(set(installed) - listed)


def current_chart(org: dict) -> str:
    return render(org, agent_files(INSTALLED_DIR), agent_files(CATALOG_DIR), PROFILE.exists())


def block(org: dict) -> str:
    return f"{START}\n{current_chart(org)}\n{END}"


def load_org() -> dict:
    return json.loads(ORG.read_text(encoding="utf-8"))


def main() -> int:
    org = load_org()
    missing = unplaced_agents(org, agent_files(INSTALLED_DIR))
    if missing:
        raise SystemExit(
            "These installed agents are not in any area of org.json: " + ", ".join(missing)
        )
    text = README.read_text(encoding="utf-8")
    if START not in text or END not in text:
        raise SystemExit(f"README.md has no ORG markers; add:\n{START}\n{END}")
    head, rest = text.split(START, 1)
    _, tail = rest.split(END, 1)
    README.write_text(head + block(org) + tail, encoding="utf-8")
    print("Wrote the organization chart to README.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
